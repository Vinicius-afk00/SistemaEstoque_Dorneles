    private void jBtnBuscaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnBuscaActionPerformed
        // TODO add your handling code here:
        String busca = jTxtBusca.getText();

        if(busca.isEmpty()){
            reflashTabelea();
        }else{
            UsuarioEntity prod = dao.buscar(Integer.parseInt(busca));
            List<UsuarioEntity> list = new ArrayList();
            list.add(prod);
            model.setLista(list);
        }

    }//GEN-LAST:event_jBtnBuscaActionPerformed

    private void jBtnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnAlterarActionPerformed
        // TODO add your handling code here:
        int id = jTbUsuarios.getSelectedRow();
        if(id<0)
        JOptionPane.showMessageDialog(this, "Selecione um produto antes");
        else{
            UsuarioEntity usu = model.getLista().get(id);
            UsuarioForm telaForm = new UsuarioForm(null, true);
            telaForm.setTelaAnterior(this);
            telaForm.PreencheForm(usu);
            telaForm.setVisible(true);
        }
    }//GEN-LAST:event_jBtnAlterarActionPerformed

    private void jBtnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnExcluirActionPerformed
        // TODO add your handling code here:
        int id = jTbUsuarios.getSelectedRow();

        if(id<0)
        JOptionPane.showMessageDialog(this, "Selecione um produto antes");
        else{
            UsuarioEntity usu = model.getLista().get(id);
            dao.deletar(usu.getId());
            JOptionPane.showMessageDialog(this, "Excluído com sucesso!");
            reflashTabelea();
        }

    }//GEN-LAST:event_jBtnExcluirActionPerformed

